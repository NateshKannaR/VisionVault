#!/usr/bin/env node
/**
 * generate-report.js — Renders eval_report.md from measured results.
 *
 * This script contains NO benchmark numbers. Every figure it prints is read from a results
 * file produced by an actual run:
 *
 *   eval/results/live-eval.json    written by `node eval/run-full-eval.js` — a real Chrome
 *                                  session with the extension installed (automated).
 *   eval/results/manual-eval.json  optional, hand-recorded observations for anything that
 *                                  cannot be automated (see manual-eval.example.json).
 *
 * If neither file exists it refuses to write a report, rather than emitting placeholders that
 * could be mistaken for measurements.
 *
 * Every row is labelled AUTOMATED or MANUAL so a reader always knows which is which.
 *
 * Usage:
 *   node eval/generate-report.js
 */

const fs = require('fs');
const path = require('path');
const M = require('./lib/metrics');

const ROOT = path.resolve(__dirname, '..');
const RESULTS_DIR = path.join(__dirname, 'results');
const LIVE_PATH = path.join(RESULTS_DIR, 'live-eval.json');
const MANUAL_PATH = path.join(RESULTS_DIR, 'manual-eval.json');
const REPORT_PATH = path.join(ROOT, 'eval_report.md');

const live = fs.existsSync(LIVE_PATH) ? JSON.parse(fs.readFileSync(LIVE_PATH, 'utf8')) : null;
const manual = fs.existsSync(MANUAL_PATH) ? JSON.parse(fs.readFileSync(MANUAL_PATH, 'utf8')) : null;

// Optional. Produced by `node eval/real-sites.js`; absent on a fixtures-only run.
const REAL_SITES_PATH = path.join(RESULTS_DIR, 'real-sites.json');
const realSites = fs.existsSync(REAL_SITES_PATH)
  ? JSON.parse(fs.readFileSync(REAL_SITES_PATH, 'utf8'))
  : null;

if (!live && !manual) {
  console.error(
    'No measurements found. Nothing will be written.\n\n' +
    `  expected: ${path.relative(ROOT, LIVE_PATH)} (from: node eval/run-full-eval.js)\n` +
    `        or: ${path.relative(ROOT, MANUAL_PATH)} (copy manual-eval.example.json and fill it in)\n\n` +
    'This script will not emit placeholder numbers.'
  );
  process.exit(1);
}

const pct = (v, d = 1) => (v === null || v === undefined || Number.isNaN(v) ? 'n/a' : `${(v * 100).toFixed(d)}%`);
const ms = (v) => (v === null || v === undefined || Number.isNaN(v) ? 'n/a' : `${Math.round(v)}ms`);
const num = (v, d = 0) => (v === null || v === undefined || Number.isNaN(v) ? 'n/a' : Number(v).toFixed(d));

const out = [];
const W = (s = '') => out.push(s);

W('# VisionVault — Evaluation Report');
W();
W('Every number in this report was measured. Nothing here is estimated, projected, or');
W('hand-written. The report is regenerated by `node eval/generate-report.js` from the JSON');
W('files that the evaluation runs leave in `eval/results/`; if those files are absent the');
W('generator refuses to produce a report at all.');
W();

// ── Provenance ──────────────────────────────────────────────────────────────
W('## How these numbers were produced');
W();
if (live) {
  const env = live.environment || {};
  W('**AUTOMATED** — `node eval/run-full-eval.js`');
  W();
  W('A real Chrome window is launched and `extension/` is installed unpacked, exactly as a user');
  W('would install it. The evaluation then calls the extension service worker\'s own');
  W('`scanAndRedact()` for each fixture tab, so the figures come from the shipped pipeline:');
  W('DOM scan across all same-origin frames, UltraFace ONNX, Tesseract OCR, region merge, and');
  W('OffscreenCanvas redaction. Ground truth is read from each fixture\'s `data-gt-*`');
  W('annotations using the elements\' real rendered geometry in the live layout, re-read');
  W('immediately before every scan. The redacted PNG that the pipeline returns is decoded and');
  W('its pixels are sampled inside every ground-truth region, so the leak check is a pixel');
  W('measurement rather than bookkeeping.');
  W();
  W('| Setting | Value |');
  W('| :--- | :--- |');
  W(`| Run at | ${live.generatedAt} |`);
  W(`| Chrome | ${env.chrome || 'n/a'} |`);
  W(`| Node | ${env.node || 'n/a'} |`);
  W(`| Platform | ${env.platform || 'n/a'} |`);
  W(`| Planning backend | ${env.planner || 'n/a'} |`);
  W(`| Redaction mode | ${env.redactMode || 'n/a'} |`);
  W(`| Scans per page | ${env.repeatsPerPage} |`);
  W(`| Match threshold | a prediction counts as covering a region when it hides ≥ ${pct(env.coverThreshold, 0)} of it |`);
  W();
}
if (manual) {
  W('**MANUAL** — hand-recorded observations from `eval/results/manual-eval.json`');
  W();
  W(`Recorded by: ${manual.recordedBy || 'unspecified'} on ${manual.recordedAt || 'unspecified date'}`);
  if (manual.method) W(`Method: ${manual.method}`);
  W();
}
if (!manual) {
  W('No manual observations file is present, so every figure below is labelled **AUTOMATED**.');
  W('To add hand-recorded results, copy `eval/results/manual-eval.example.json` to');
  W('`eval/results/manual-eval.json`, fill it in, and re-run this generator.');
  W();
}

// ── Headline ────────────────────────────────────────────────────────────────
if (live) {
  const o = live.overall;
  W('---');
  W();
  W('## Headline results (AUTOMATED)');
  W();
  W(`Across ${o.pageCount} fixture pages, ${live.environment.repeatsPerPage} scans each,`);
  W(`${o.totalGroundTruthRegions} annotated sensitive regions in total.`);
  W();
  W('| Metric | Result | What it measures |');
  W('| :--- | :---: | :--- |');
  W(`| PII recall | **${pct(o.piiRecall)}** | share of annotated sensitive regions covered by a redaction box |`);
  W(`| PII precision | **${pct(o.piiPrecision)}** | redactions that hid something annotated sensitive, not something annotated safe |`);
  W(`| Redaction tightness (IoU) | **${pct(o.piiMeanIoU)}** | how closely each mask matches the region it hides |`);
  W(`| Pixel leaks | **${o.totalPixelLeaks}** | regions whose original ink survived into the returned PNG |`);
  W(`| Surviving ink | **${pct(o.meanSurvivingInk, 2)}** | share of each region's original ink left unpainted (lower is better) |`);
  W(`| Mean masked fraction | **${pct(o.meanMaskedFraction)}** | share of ground-truth pixels actually painted over |`);
  W(`| Visual-context recall | **${pct(o.markRecall)}** | interactive elements the agent tagged, of those it should |`);
  W(`| Role accuracy | **${pct(o.markRoleAccuracy)}** | tagged elements given the correct role |`);
  W(`| Mark box IoU | **${pct(o.markMeanIoU)}** | geometric accuracy of the reported element boxes |`);
  W(`| Mark ID stability | **${o.markIdsStable ? 'stable' : 'UNSTABLE'}** | identical IDs across repeated scans of the same page |`);
  W(`| Mean scan latency | **${ms(o.meanLatencyMs)}** | full local pipeline, capture to redacted image |`);
  W(`| p95 scan latency | **${ms(o.p95LatencyMs)}** | worst case across all runs |`);
  W();

  // ── Per page ──
  W('### Per page');
  W();
  W('| Page | Regions | Recall | Precision | IoU | Pixel leaks | Marks | Role acc. | Latency |');
  W('| :--- | :---: | :---: | :---: | :---: | :---: | :---: | :---: | :---: |');
  for (const p of live.pages) {
    W(
      `| ${p.label} | ${p.groundTruth.pii} | ${pct(p.piiRecall)} | ${pct(p.piiPrecision)} | ` +
      `${pct(p.piiMeanIoU)} | ${p.pixelLeaks} | ${pct(p.markRecall)} | ${pct(p.markRoleAccuracy)} | ${ms(p.latency.total)} |`
    );
  }
  W();
  W('Each row is the mean of its repeats. The redacted frame from the first scan of each page');
  W('is saved next to the results as `eval/results/redacted-<page>.png`, so the masking can be');
  W('inspected by eye rather than taken on trust.');
  W();

  // ── Where each detector earns its place ──
  W('### What each detector contributed');
  W();
  W('| Page | DOM | Face | OCR | Regions only OCR could cover |');
  W('| :--- | :---: | :---: | :---: | :---: |');
  for (const p of live.pages) {
    const sb = p.sourceBreakdown || {};
    const cb = p.coveredBy || {};
    W(`| ${p.label} | ${sb.dom ?? 0} | ${sb.vision_face ?? 0} | ${sb.vision_ocr ?? 0} | ${cb.ocrOnly ?? 0} |`);
  }
  W();
  W(`Across the suite, **${o.regionsCoveredByOcrOnly}** ground-truth regions were covered only by`);
  W('OCR-sourced detections — no DOM rule and no face box reached them.');
  W();

  // ── Latency / accuracy trade-off ──
  W('### Latency vs coverage (the trade-off, measured)');
  W();
  W('The same pages, the same pipeline, scanned twice: once with OCR on, once with it off.');
  W();
  W('| Profile | Mean latency | PII recall | Pixel leaks |');
  W('| :--- | :---: | :---: | :---: |');
  W(`| Full — DOM + face + OCR | ${ms(o.meanLatencyMs)} | ${pct(o.piiRecall)} | ${o.totalPixelLeaks} |`);
  W(`| Fast — DOM + face, no OCR | ${ms(o.fastLatencyMs)} | ${pct(o.fastPiiRecall)} | ${o.fastPixelLeaks} |`);
  W();
  W('| Stage | Mean cost |');
  W('| :--- | :---: |');
  W(`| Screen capture + DOM scan (all frames) | ${ms(o.meanCaptureMs)} |`);
  W(`| UltraFace ONNX (WASM SIMD) | ${ms(o.meanFaceMs)} |`);
  W(`| Tesseract OCR (WASM) | ${ms(o.meanOcrMs)} |`);
  W(`| OffscreenCanvas redaction | ${ms(o.meanRedactMs)} |`);
  W();
  W('OCR dominates the budget. On pages whose text lives in the DOM it changes nothing, because');
  W('the DOM rules already found that text — which is why the fast profile scores the same');
  W('recall on most pages. It earns its cost only where text exists purely as pixels; the');
  W('`pixel-receipt` fixture is exactly that case, and the per-page table above shows what');
  W('happens there with OCR disabled. The side panel exposes this as a **Local Vision Depth**');
  W('setting so the choice is the user\'s, not a hidden default.');
  W();

  // ── Resources ──
  const ru = live.resourceUtilisation || {};
  const b = ru.bundle || {};
  W('### Client-side resource use');
  W();
  W('| Measure | Value |');
  W('| :--- | :---: |');
  W(`| Extension on disk, total | ${num(b.totalMB, 2)} MB |`);
  W(`| &nbsp;&nbsp;ML runtimes (\`lib/\`) | ${num(b.libMB, 2)} MB |`);
  W(`| &nbsp;&nbsp;Model weights (\`models/\`) | ${num(b.modelsMB, 2)} MB |`);
  W(`| &nbsp;&nbsp;Extension code | ${num(b.codeMB, 2)} MB |`);
  if (ru.offscreenHeap) {
    W(`| Offscreen JS heap in use, after scanning | ${num(ru.offscreenHeap.usedJSHeapMB, 1)} MB |`);
    W(`| Offscreen JS heap allocated | ${num(ru.offscreenHeap.totalJSHeapMB, 1)} MB |`);
  }
  W();
  W('Inference runs in an MV3 offscreen document, off the page\'s main thread, so a scan does');
  W('not block the page the user is reading.');
  W();

  // ── End to end ──
  const e = live.endToEnd;
  W('### End-to-end task');
  W();
  if (!e || e.error) {
    W(`The end-to-end run did not complete: \`${(e && e.error) || 'not attempted'}\`.`);
  } else {
    W('One full task — *"Fill the signup form with my details"* — from a cleared form, planned by');
    W(`the live server chain (${live.environment.planner}).`);
    W();
    W('| Measure | Value |');
    W('| :--- | :---: |');
    W(`| Initial scan (local pipeline) | ${ms(e.scanMs)} |`);
    W(`| Agent loop, ${e.steps} steps | ${ms(e.runMs)} |`);
    W(`| Total wall clock | ${ms(e.totalMs)} |`);
    W(`| Sensitive regions redacted before first upload | ${e.piiCount} |`);
    W(`| Interactive elements offered to the planner | ${e.markCount} |`);
    W(`| Loop terminated cleanly | ${e.done ? 'yes' : 'no'} |`);
    W();
    W('Field values after the run — every one resolved from the local vault on-device, none of');
    W('them ever sent to the server:');
    W();
    W('```json');
    W(JSON.stringify(e.fieldsAfterRun, null, 2));
    W('```');
    W();
    W('Per-step latency is dominated by the cloud planner, not by the client. The local scan');
    W(`costs ${ms(e.scanMs)}; each planning call to the hosted model took seconds.`);
  }
  W();
}

// ── Manual observations ─────────────────────────────────────────────────────
if (manual) {
  W('---');
  W();
  W('## Hand-recorded observations (MANUAL)');
  W();
  if (Array.isArray(manual.observations) && manual.observations.length) {
    W('| # | Check | Result | Evidence |');
    W('| :-: | :--- | :---: | :--- |');
    manual.observations.forEach((o, i) => {
      W(`| ${i + 1} | ${o.check || ''} | ${o.result || ''} | ${o.evidence || ''} |`);
    });
    W();
  }
  if (manual.notes) {
    W(manual.notes);
    W();
  }
}

// ── Method ──────────────────────────────────────────────────────────────────
// ── Real websites ───────────────────────────────────────────────────────────
//
// The fixture suite measures detection quality against known ground truth. It cannot measure
// whether the agent works on a site nobody annotated, so this section reports exactly that,
// with no ground truth and no partial credit: either the thing the user asked for happened on
// the page, or it did not.
if (realSites && Array.isArray(realSites.sites) && realSites.sites.length) {
  W('---');
  W();
  W('## On real websites');
  W();
  W('`node eval/real-sites.js` drives the shipped extension against public sites with read-only');
  W('tasks — search and scroll. Nothing is bought, submitted or logged into. Success is judged');
  W('from the page afterwards, not from the agent\'s own report: for a search task the query has');
  W('to appear in the URL, the title or a field.');
  W();
  W(`Run at ${realSites.generatedAt}, planner \`${realSites.planner}\`, ${realSites.budgetSeconds}s budget per site.`);
  W();
  W('| Site | Category | Task | Steps | Milestones | Local scan | Masked | Outcome |');
  W('| :--- | :--- | :--- | ---: | ---: | ---: | ---: | :--- |');

  let landed = 0;
  let acted = 0;
  let searchTasks = 0;
  let blockedCount = 0;
  let readTasks = 0;
  let answered = 0;
  const stepTimes = [];

  for (const s of realSites.sites) {
    const q = s.queryOnPage;
    let outcome;
    // Older result files predate the explicit flag; the reason the agent gave still says it.
    const blocked = s.botWall || /verification page|asking for a human|CAPTCHA/i.test(s.stopReason || '');
    if (blocked) {
      // Not a failure of the agent: the site asked for a human and the agent said so.
      outcome = 'stopped — the site asked for human verification';
      blockedCount++;
    } else if (s.error) {
      outcome = `error: ${s.error}`;
    } else if (q) {
      searchTasks++;
      const where = [q.inUrl && 'URL', q.inTitle && 'title', q.inBox && 'field'].filter(Boolean).join(' + ');
      if (q.inUrl || q.inTitle) { landed++; outcome = `**searched** (in ${where})`; }
      else if (q.inBox) { outcome = 'typed, but the site did not run it'; }
      else { outcome = 'search did not land'; }
    } else if (s.wantedRead) {
      readTasks++;
      if (s.answered) {
        answered++;
        outcome = s.itemsRead ? `**read ${s.itemsRead} items and answered**` : '**read the page and answered**';
      } else {
        outcome = 'read nothing';
      }
    } else if (s.steps) {
      acted++;
      outcome = '**acted**';
    } else {
      outcome = 'no action';
    }
    if (s.steps && s.runMs) stepTimes.push(s.runMs / s.steps);
    const miles = s.milestonesTotal ? `${s.milestonesDone}/${s.milestonesTotal}` : '-';
    W(`| ${s.site} | ${s.group || '-'} | ${s.task} | ${s.steps ?? '-'} | ${miles} | ${ms(s.pipelineMs)} | ${s.pii ?? '-'} | ${outcome} |`);
  }

  W();
  W(`**${landed} of ${searchTasks} search tasks reached the results page**, ` +
    `${answered} of ${readTasks} read-and-answer task${readTasks === 1 ? '' : 's'} produced an answer, and ` +
    `${acted} other task${acted === 1 ? '' : 's'} carried out the requested action` +
    (blockedCount
      ? `. ${blockedCount} site${blockedCount === 1 ? '' : 's'} refused automation outright with a ` +
        'human-verification challenge, which the agent detects and reports rather than trying to get around'
      : '') +
    '. Every remaining case is reported by the agent as unfinished, with the reason, rather than ' +
    'being claimed as a success.');
  W();
  if (stepTimes.length) {
    stepTimes.sort((a, b) => a - b);
    const mean = stepTimes.reduce((x, y) => x + y, 0) / stepTimes.length;
    W();
    W(`Per-step wall clock across every site that acted: mean ${ms(mean)}, median ` +
      `${ms(stepTimes[Math.floor(stepTimes.length / 2)])}, worst ${ms(stepTimes[stepTimes.length - 1])}. ` +
      'That includes the full local scan — capture, DOM across all frames, face and OCR ' +
      'inference, region merge and redaction — as well as the planning round trip, because ' +
      'both happen on every step.');
  }

  W();
  W('The "Milestones" column is the honest one. A task decomposed into five stages that ' +
    'completes three of them is reported as `3/5` and as a *partial* outcome, with the skipped ' +
    'stages and the reason named on the completion card. A milestone the page offers no way to ' +
    'satisfy — a price filter a site does not have — is abandoned after four attempts so the ' +
    'stages after it still run.');
  W();
  W('The "Masked" column is worth reading alongside the fixture numbers. On a shopping home');
  W('page it is small because the face model — not a blanket rule over every image — decides');
  W('which pixels hold a face; on a news site it is non-zero because the model found real');
  W('faces in the photography. Before that change the same Amazon page reported 71 masked');
  W('regions, almost all of them product photos.');
  W();
}

W('---');
W();
W('## How each metric is defined');
W();
W('**PII recall** — of the regions a fixture annotates as sensitive, the share covered by at');
W('least one redaction box. Matching uses *coverage of the truth region*, not IoU: a mask');
W('larger than the region still hides the data, and penalising it would reward masks that are');
W('tight enough to leak at the edges.');
W();
W('**PII precision** — a redaction counts against precision only when it hides an element the');
W('fixture explicitly annotates as safe (`data-gt-safe`). Boxes that overlap nothing annotated');
W('are neither rewarded nor penalised, because the fixture makes no claim about them.');
W();
W('**Redaction tightness (IoU)** — mean intersection-over-union of each matched mask with the');
W('region it covers. This is where over-redaction shows up: a mask that blacks out half the');
W('page would score perfect recall and poor IoU.');
W();
W('**Pixel leaks** — the returned PNG is decoded and compared, pixel by pixel, against an');
W('unredacted reference capture taken by the harness. Inside each ground-truth box, the');
W("reference's median luma gives the local background; every pixel differing from it by more");
W('than 35 is *ink* — the pixels that carry the information. A region leaks when more than 2%');
W('of its ink is byte-for-byte unchanged in the redacted frame, i.e. was never painted over.');
W();
W('Comparing against the reference is what makes this a measurement rather than a proxy. The');
W('obvious alternative — "what fraction of the box is black?" — punishes a tight mask for the');
W('harmless margin around it and rewards a mask so large it swallows the page. It also cannot');
W('score mosaic mode at all. This test is mode-agnostic: a blur fill changes the pixels too.');
W();
W('As a further guard against a trivially perfect score, safe regions are sampled as well: if');
W('the whole frame were blacked out the leak count would be zero but the image would be');
W('useless to the planner, so the runner records how many safe regions remain legible.');
W();
W('**Visual-context recall / role accuracy** — of the elements a fixture annotates as');
W('interactive, the share the agent tagged, and of those, the share given the right role.');
W('This is the metric for how faithfully the sanitized payload describes the screen.');
W();
W('**Mark ID stability** — the same page is scanned repeatedly and the sets of element IDs');
W('compared. IDs are hashes of each element\'s identity and document-space geometry, so an');
W('action planned against one scan still resolves on the next.');
W();

W('## Reproducing this');
W();
W('```bash');
W('# optional: start the planning server (without it the client-side planner is used)');
W('cd server && pip install -r requirements.txt && python main.py');
W();
W('# from the repository root');
W('npm install --no-save puppeteer-core');
W('node eval/run-full-eval.js --repeats 3');
W('node eval/generate-report.js');
W('```');
W();
W('A real Chrome window opens and drives itself; leave it in the foreground, since');
W('`captureVisibleTab` only captures the foreground tab. Set `VV_CHROME` if Chrome is not at');
W('the default install path. `node eval/diagnose.js <fixture.html>` prints one scan\'s full');
W('stage-by-stage trace when a number needs explaining.');
W();

fs.writeFileSync(REPORT_PATH, out.join('\n'));
console.log(`Wrote ${path.relative(ROOT, REPORT_PATH)}`);
console.log(`  sources: ${live ? 'live-eval.json (AUTOMATED)' : ''}${live && manual ? ' + ' : ''}${manual ? 'manual-eval.json (MANUAL)' : ''}`);
if (live) {
  console.log(`  ${live.pages.length} pages, ${live.environment.repeatsPerPage} scans each, measured ${live.generatedAt}`);
}
